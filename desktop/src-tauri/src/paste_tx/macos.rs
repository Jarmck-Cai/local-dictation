use std::sync::{mpsc, Arc, Mutex};
use std::time::{Duration, Instant};
use tauri::AppHandle;

/// Concealment marker types declared alongside the text so that well-behaved
/// third-party clipboard managers (Maccy, Paste, ...) skip the transcript.
/// Fewer eager readers means a receipt is more likely to be the actual target.
/// These are conventions; nothing enforces them.
const CONCEALMENT_TYPES: [&str; 3] = [
    "org.nspasteboard.TransientType",
    "org.nspasteboard.ConcealedType",
    "org.nspasteboard.AutoGeneratedType",
];

pub struct ProviderIvars {
    state: Arc<Mutex<TxState>>,
    text: String,
}

define_class!(
    // SAFETY: NSObject has no subclassing requirements and the ivars are
    // plain Rust values guarded by a Mutex.
    #[unsafe(super(NSObject))]
    #[name = "HandyPasteProvider"]
    #[ivars = ProviderIvars]
    pub struct HandyPasteProvider;

    impl HandyPasteProvider {
        // NSPasteboardOwner informal protocol: the pasteboard is asking for the
        // promised data â€” our receipt that a consumer read the clipboard.
        #[unsafe(method(pasteboard:provideDataForType:))]
        fn pasteboard_provide_data_for_type(&self, pasteboard: &NSPasteboard, data_type: &NSString) {
            let ivars = self.ivars();
            // SAFETY: NSPasteboardTypeString is a read-only framework static.
            let is_text = unsafe { data_type.isEqualToString(NSPasteboardTypeString) };
            // Only a text read counts as a receipt: a request for one of the
            // concealment marker types is a clipboard manager inspecting the
            // markers, not the paste target reading the transcript.
            let payload = if is_text {
                NSString::from_str(&ivars.text)
            } else {
                // Concealment marker types are never handed out.
                NSString::from_str("")
            };
            let supplied = pasteboard.setString_forType(&payload, data_type);
            if is_text {
                if let Ok(mut state) = ivars.state.lock() {
                    if supplied {
                        state.record_receipt(Instant::now());
                    } else {
                        state.injection_failed = true;
                    }
                }
            }
        }

        #[unsafe(method(pasteboardChangedOwner:))]
        fn pasteboard_changed_owner(&self, _pasteboard: &NSPasteboard) {
            if let Ok(mut state) = self.ivars().state.lock() {
                state.ownership_lost = true;
            }
        }
    }
);

impl HandyPasteProvider {
    fn new(state: Arc<Mutex<TxState>>, text: String) -> Retained<Self> {
        let this = Self::alloc().set_ivars(ProviderIvars { state, text });
        unsafe { msg_send![super(this), init] }
    }
}

type Snapshot = Vec<Retained<ProtocolObject<dyn NSPasteboardWriting>>>;

const MAX_SNAPSHOT_BYTES: usize = 32 * 1024 * 1024;

fn snapshot(pasteboard: &NSPasteboard) -> Result<Snapshot, String> {
    let mut copied = Vec::new();
    let mut bytes = 0usize;
    if let Some(items) = pasteboard.pasteboardItems() {
        if items.len() > 256 {
            return Err("manual_paste_backup_too_large".into());
        }
        for item in items.iter() {
            let copy = NSPasteboardItem::new();
            let types = item.types();
            if types.is_empty() || types.len() > 128 {
                return Err("manual_paste_backup_failed".into());
            }
            for kind in types.iter() {
                let name = kind.to_string();
                if name.contains("filepromise") || name == "NSFilesPromisePboardType" {
                    return Err("manual_paste_unsupported_format".into());
                }
                let data = item
                    .dataForType(&kind)
                    .ok_or("manual_paste_backup_failed")?;
                bytes = bytes
                    .checked_add(data.len())
                    .filter(|&total| total <= MAX_SNAPSHOT_BYTES)
                    .ok_or("manual_paste_backup_too_large")?;
                if !copy.setData_forType(&data, &kind) {
                    return Err("manual_paste_backup_failed".into());
                }
            }
            copied.push(ProtocolObject::from_retained(copy));
        }
    }
    Ok(copied)
}

fn foreground_pid() -> Option<i32> {
    NSWorkspace::sharedWorkspace()
        .frontmostApplication()
        .map(|app| app.processIdentifier())
        .filter(|&pid| pid > 0)
}

fn preflight(cancelled: &dyn Fn() -> bool) -> Result<(), String> {
    if cancelled() {
        return Err("manual_paste_cancelled".into());
    }
    match crate::manual_paste::any_keyboard_key_down() {
        Ok(false) => Ok(()),
        Ok(true) => Err("keys_held".into()),
        Err(code) => Err(code.into()),
    }
}

fn on_main<T: Send + 'static>(
    app: &AppHandle,
    execute: impl FnOnce() -> Result<T, String> + Send + 'static,
) -> Result<T, String> {
    let (reply, result) = mpsc::sync_channel(1);
    app.run_on_main_thread(move || {
        let _ = reply.send(execute());
    })
    .map_err(|_| "manual_paste_unavailable")?;
    result.recv().map_err(|_| "manual_paste_unavailable")?
}

// Keep ObjC pasteboard items and their owner in the UI thread. Only the receipt
// state and a settlement closure are transferred between worker and main.
struct Pending {
    state: Arc<Mutex<TxState>>,
    saved: Snapshot,
    change_count: NSInteger,
    _provider: Retained<HandyPasteProvider>,
    injection: Result<(), String>,
}

impl Pending {
    fn finish(
        self,
        text: &str,
        handling: ClipboardHandling,
        cancelled: bool,
    ) -> Result<bool, String> {
        let (read, lost, failed) = {
            let st = self.state.lock().map_err(|_| "manual_paste_unavailable")?;
            (
                st.any_receipt_after_injection(),
                st.ownership_lost,
                st.injection_failed,
            )
        };
        let pasteboard = NSPasteboard::generalPasteboard();
        if lost || pasteboard.changeCount() != self.change_count {
            return Err("manual_paste_clipboard_changed".into());
        }
        let copy = !cancelled
            && match handling {
                ClipboardHandling::CopyToClipboard => self.injection.is_ok(),
                ClipboardHandling::CopyOnFailure => !read || failed,
                ClipboardHandling::DontModify => false,
            };
        pasteboard.clearContents();
        if copy {
            if !pasteboard
                .setString_forType(&NSString::from_str(text), unsafe { NSPasteboardTypeString })
            {
                return Err("manual_paste_restore_failed".into());
            }
        } else if !self.saved.is_empty()
            && !pasteboard.writeObjects(&NSArray::from_retained_slice(&self.saved))
        {
            return Err("manual_paste_restore_failed".into());
        }
        if cancelled {
            return Err("manual_paste_cancelled".into());
        }
        self.injection?;
        if failed {
            return Err("manual_paste_render_failed".into());
        }
        Ok(read)
    }
}

thread_local! {
    // The coordinator holds a single permit across automatic and manual output.
    static PENDING: std::cell::RefCell<Option<Pending>> = const { std::cell::RefCell::new(None) };
}

fn begin(
    text: &str,
    app: &AppHandle,
    method: PasteMethod,
    cancelled: &dyn Fn() -> bool,
) -> Result<Arc<Mutex<TxState>>, String> {
    preflight(cancelled)?;
    let target = foreground_pid().ok_or("input_target_unavailable")?;
    if PENDING.with(|slot| slot.borrow().is_some()) {
        return Err("manual_paste_unavailable".into());
    }
    with_enigo(app, |enigo| {
        let pasteboard = NSPasteboard::generalPasteboard();
        let baseline = pasteboard.changeCount();
        let saved = snapshot(&pasteboard)?;
        preflight(cancelled)?;
        if foreground_pid() != Some(target) {
            return Err("input_target_changed".into());
        }
        if pasteboard.changeCount() != baseline {
            return Err("manual_paste_clipboard_changed".into());
        }
        let state = Arc::new(Mutex::new(TxState::new()));
        let provider = HandyPasteProvider::new(state.clone(), text.to_string());
        let mut types = vec![NSString::from_str("public.utf8-plain-text")];
        types.extend(CONCEALMENT_TYPES.map(NSString::from_str));
        let types = NSArray::from_retained_slice(&types);
        let change_count: NSInteger =
            unsafe { msg_send![&*pasteboard, declareTypes: &*types, owner: &*provider] };
        let injection = preflight(cancelled).and_then(|()| {
            if change_count <= 0 {
                return Err("manual_paste_publish_failed".into());
            }
            if foreground_pid() != Some(target) {
                return Err("input_target_changed".into());
            }
            if pasteboard.changeCount() != change_count {
                return Err("manual_paste_clipboard_changed".into());
            }
            state
                .lock()
                .map_err(|_| "manual_paste_unavailable")?
                .injected_at = Some(Instant::now());
            send_chord(enigo, &method).map_err(|_| "manual_paste_injection_failed".into())
        });
        if injection.is_err() {
            state
                .lock()
                .map_err(|_| "manual_paste_unavailable")?
                .injection_failed = true;
        }
        PENDING.with(|slot| {
            *slot.borrow_mut() = Some(Pending {
                state: state.clone(),
                saved,
                change_count,
                _provider: provider,
                injection,
            });
        });
        Ok(state)
    })
}

pub(crate) fn run(
    text: String,
    app: &AppHandle,
    method: PasteMethod,
    handling: ClipboardHandling,
    cancelled: impl Fn() -> bool + Send + Sync + 'static,
) -> Result<bool, String> {
    let deadline = Instant::now() + Duration::from_millis(800);
    loop {
        match preflight(&cancelled) {
            Err(code) if code == "keys_held" && Instant::now() < deadline => {
                std::thread::sleep(Duration::from_millis(10));
            }
            result => {
                result?;
                break;
            }
        }
    }
    let text = Arc::new(text);
    let cancelled = Arc::new(cancelled);
    let state = on_main(app, {
        let app = app.clone();
        let text = Arc::clone(&text);
        let cancelled = Arc::clone(&cancelled);
        move || begin(&text, &app, method, &*cancelled)
    })?;
    loop {
        let finish = match state.lock() {
            Ok(st) => matches!(evaluate(&st, Instant::now()), WaitDecision::Finish),
            Err(_) => true,
        };
        if finish || cancelled() {
            break;
        }
        std::thread::sleep(Duration::from_millis(15));
    }
    on_main(app, move || {
        let pending = PENDING
            .with(|slot| slot.borrow_mut().take())
            .ok_or("manual_paste_unavailable")?;
        pending.finish(&text, handling, cancelled())
    })
}
